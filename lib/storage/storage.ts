/**
 * Private object storage. Implementations must never expose objects through
 * public URLs; reads go through server code that has already checked ownership.
 *
 * Future drivers (S3, R2, Supabase Storage) implement the same interface.
 */
export interface FileStorage {
  readonly driver: string;
  put(key: string, data: Uint8Array, contentType: string): Promise<void>;
  get(key: string): Promise<Uint8Array>;
  /** Idempotent: deleting a missing object is not an error. */
  delete(key: string): Promise<void>;
}

export class StorageError extends Error {
  constructor(
    readonly code: "INVALID_KEY" | "NOT_FOUND" | "IO",
    message: string,
  ) {
    super(message);
    this.name = "StorageError";
  }
}

/**
 * Keys are generated by the server only (see cvStorageKey). This allowlist is
 * defence in depth: no dots, backslashes, absolute paths or empty segments.
 */
const KEY_PATTERN = /^[a-z0-9_-]+(\/[a-z0-9_-]+)*$/i;

export function assertValidStorageKey(key: string): void {
  if (key.length > 200 || !KEY_PATTERN.test(key)) {
    throw new StorageError("INVALID_KEY", "Invalid storage key");
  }
}
