import { CircleCheck, CircleDashed, CircleX, Flag, Info, Lightbulb } from "lucide-react";
import { ProgressBar } from "@/components/roadmap/progress-bar";
import { TaskCard } from "@/components/roadmap/task-card";
import { Badge } from "@/components/ui/badge";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import type { MyRoadmap } from "@/lib/data/roadmap";
import { GAP_STATUS_LABELS, PRIORITY_LABELS, type GapStatus } from "@/lib/roadmap/constants";
import { progressByPhase } from "@/lib/roadmap/progress";
import type { RoadmapReport as Report, ReportSkillGap } from "@/lib/roadmap/schema";
import { cn } from "@/lib/utils";

const NOT_SPECIFIED = "Not specified";

function Overview({ roadmap, report }: { roadmap: MyRoadmap; report: Report }) {
  const { timeline } = report;
  const overTarget =
    timeline.timeframeWeeks !== null && timeline.totalWeeks > timeline.timeframeWeeks;
  return (
    <Card>
      <CardHeader>
        <CardTitle role="heading" aria-level={2}>
          Overview
        </CardTitle>
        <CardDescription>{report.sourceLabel}</CardDescription>
      </CardHeader>
      <CardContent className="grid gap-5">
        {roadmap.provider === "mock" && (
          <p className="flex items-start gap-2 rounded-lg border border-warning/40 bg-warning/5 px-3 py-2 text-xs">
            <Info className="mt-0.5 size-3.5 shrink-0 text-warning" aria-hidden />
            Generated by the deterministic mock provider for development. It is not an AI
            assessment.
          </p>
        )}
        <ProgressBar progress={roadmap.progress} label={report.title} />
        <dl className="grid grid-cols-1 gap-3 text-sm sm:grid-cols-3">
          <div className="min-w-0">
            <dt className="text-xs text-muted-foreground">Target</dt>
            <dd className="mt-0.5 font-medium break-words">
              {report.target.title}
              {report.target.company && (
                <span className="font-normal text-muted-foreground">
                  {" "}
                  · {report.target.company}
                </span>
              )}
            </dd>
          </div>
          <div>
            <dt className="text-xs text-muted-foreground">Roadmap type</dt>
            <dd className="mt-0.5 font-medium">
              {report.target.type === "job" ? "Job roadmap" : "Career-goal roadmap"}
            </dd>
          </div>
          <div>
            <dt className="text-xs text-muted-foreground">Estimated duration</dt>
            <dd className="mt-0.5 font-medium">
              ~{timeline.totalWeeks} week{timeline.totalWeeks === 1 ? "" : "s"}
              {timeline.timeframeWeeks !== null && (
                <span className="font-normal text-muted-foreground">
                  {" "}
                  (target {timeline.timeframeWeeks} weeks)
                </span>
              )}
            </dd>
          </div>
        </dl>
        {overTarget && (
          <p className="text-xs text-muted-foreground">
            Realistic estimates add up to more than your {timeline.timeframeWeeks}-week target.
            Focus on critical and high-priority tasks first, or plan for the longer timeline.
          </p>
        )}
        <p className="text-sm text-muted-foreground">{report.summary}</p>
      </CardContent>
    </Card>
  );
}

function ListOrUnknown({ items }: { items: string[] }) {
  if (items.length === 0) return <dd className="mt-0.5 text-muted-foreground">{NOT_SPECIFIED}</dd>;
  return (
    <dd className="mt-1 flex flex-wrap gap-1.5">
      {items.map((item) => (
        <Badge
          key={item}
          variant="secondary"
          className="max-w-full font-normal break-words whitespace-normal"
        >
          {item}
        </Badge>
      ))}
    </dd>
  );
}

function CurrentProfile({ profile }: { profile: Report["currentProfile"] }) {
  return (
    <Card>
      <CardHeader>
        <CardTitle role="heading" aria-level={2}>
          Your current profile
        </CardTitle>
        <CardDescription>
          Only information verified in your CV or profile. Anything unknown is marked “
          {NOT_SPECIFIED}”.
        </CardDescription>
      </CardHeader>
      <CardContent>
        <dl className="grid grid-cols-1 gap-4 text-sm md:grid-cols-2">
          <div>
            <dt className="text-xs text-muted-foreground">Experience level</dt>
            <dd className="mt-0.5 font-medium">{profile.experienceLevel}</dd>
          </div>
          <div className="min-w-0">
            <dt className="text-xs text-muted-foreground">Education</dt>
            {profile.education.length === 0 ? (
              <dd className="mt-0.5 text-muted-foreground">{NOT_SPECIFIED}</dd>
            ) : (
              profile.education.map((line) => (
                <dd key={line} className="mt-0.5 break-words">
                  {line}
                </dd>
              ))
            )}
          </div>
          <div className="min-w-0">
            <dt className="text-xs text-muted-foreground">Strong skills</dt>
            <ListOrUnknown items={profile.strongSkills} />
          </div>
          <div className="min-w-0">
            <dt className="text-xs text-muted-foreground">Developing skills</dt>
            <ListOrUnknown items={profile.developingSkills} />
          </div>
          <div className="min-w-0">
            <dt className="text-xs text-muted-foreground">Technologies</dt>
            <ListOrUnknown items={profile.technologies} />
          </div>
          <div className="min-w-0">
            <dt className="text-xs text-muted-foreground">Relevant projects</dt>
            {profile.relevantProjects.length === 0 ? (
              <dd className="mt-0.5 text-muted-foreground">{NOT_SPECIFIED}</dd>
            ) : (
              profile.relevantProjects.map((line) => (
                <dd key={line} className="mt-0.5 break-words">
                  {line}
                </dd>
              ))
            )}
          </div>
        </dl>
      </CardContent>
    </Card>
  );
}

const GAP_GROUPS: { status: GapStatus; icon: typeof CircleCheck; tone: string; hint: string }[] = [
  {
    status: "NOT_DEMONSTRATED",
    icon: CircleX,
    tone: "text-destructive",
    hint: "Your CV doesn't show these yet. Building visible evidence of them is the focus of this plan.",
  },
  {
    status: "DEVELOPING",
    icon: CircleDashed,
    tone: "text-warning",
    hint: "Related evidence exists, but it isn't yet strong for this target.",
  },
  {
    status: "STRONG",
    icon: CircleCheck,
    tone: "text-success",
    hint: "Clearly demonstrated in your CV.",
  },
];

function GapItem({ gap }: { gap: ReportSkillGap }) {
  return (
    <li className="min-w-0 rounded-lg border p-3.5">
      <div className="flex flex-wrap items-center gap-1.5">
        <p className="text-sm font-medium break-words">{gap.skill}</p>
        <Badge variant="outline" className="font-normal">
          {PRIORITY_LABELS[gap.priority]} priority
        </Badge>
        {gap.requirementKind && (
          <Badge variant="secondary" className="font-normal">
            {gap.requirementKind === "REQUIRED" ? "Required" : "Preferred"}
          </Badge>
        )}
      </div>
      <p className="mt-1.5 text-xs text-muted-foreground">{gap.reason}</p>
      {(gap.cvEvidence || gap.targetEvidence) && (
        <dl className="mt-2 grid gap-1.5 text-xs">
          {gap.cvEvidence && (
            <div>
              <dt className="text-muted-foreground">Evidence in your CV</dt>
              <dd className="mt-0.5 border-l-2 border-success/40 pl-2 break-words">
                “{gap.cvEvidence}”
              </dd>
            </div>
          )}
          {gap.targetEvidence && (
            <div>
              <dt className="text-muted-foreground">From the job description</dt>
              <dd className="mt-0.5 border-l-2 border-muted-foreground/30 pl-2 break-words">
                “{gap.targetEvidence}”
              </dd>
            </div>
          )}
        </dl>
      )}
    </li>
  );
}

function SkillGaps({ report }: { report: Report }) {
  const { grounding } = report;
  return (
    <Card>
      <CardHeader>
        <CardTitle role="heading" aria-level={2}>
          Skill gaps
        </CardTitle>
        <CardDescription>
          {report.target.type === "job"
            ? "Each gap traces back to the job description or your Job Match result."
            : "Skills commonly expected for this career goal, checked against your CV."}
        </CardDescription>
      </CardHeader>
      <CardContent className="grid gap-6">
        {report.skillGaps.length === 0 && (
          <p className="text-sm text-muted-foreground">No skill gaps could be verified.</p>
        )}
        {GAP_GROUPS.map((group) => {
          const gaps = report.skillGaps.filter((g) => g.status === group.status);
          if (gaps.length === 0) return null;
          return (
            <section key={group.status} aria-labelledby={`gaps-${group.status}`}>
              <div className="mb-3 flex items-start gap-2">
                <group.icon className={cn("mt-0.5 size-4 shrink-0", group.tone)} aria-hidden />
                <div>
                  <h3 id={`gaps-${group.status}`} className="text-sm font-medium">
                    {GAP_STATUS_LABELS[group.status]}{" "}
                    <span className="text-muted-foreground">({gaps.length})</span>
                  </h3>
                  <p className="text-xs text-muted-foreground">{group.hint}</p>
                </div>
              </div>
              <ul className="grid grid-cols-1 gap-3 lg:grid-cols-2">
                {gaps.map((gap) => (
                  <GapItem key={gap.skill} gap={gap} />
                ))}
              </ul>
            </section>
          );
        })}
        {(grounding.removedGaps > 0 || grounding.adjustedGaps > 0) && (
          <p className="text-xs text-muted-foreground">
            Evidence check: {grounding.adjustedGaps} gap
            {grounding.adjustedGaps === 1 ? " was" : "s were"} re-classified and{" "}
            {grounding.removedGaps} unsupported gap{grounding.removedGaps === 1 ? " was" : "s were"}{" "}
            removed because they couldn&apos;t be verified against your sources.
          </p>
        )}
      </CardContent>
    </Card>
  );
}

function Timeline({ roadmap, report }: { roadmap: MyRoadmap; report: Report }) {
  const phaseProgress = progressByPhase(roadmap.items);
  return (
    <section aria-labelledby="timeline-heading" className="min-w-0">
      <h2 id="timeline-heading" className="mb-1 text-lg font-semibold tracking-tight">
        Learning phases
      </h2>
      <p className="mb-5 text-sm text-muted-foreground">
        Work through the phases in order. Tasks unlock when their prerequisites are completed.
      </p>
      <ol className="relative grid grid-cols-1 gap-8 border-l-2 border-border pl-5 sm:pl-7">
        {report.phases.map((phase) => {
          const tasks = roadmap.items.filter((t) => t.phaseOrder === phase.order);
          const progress = phaseProgress.get(phase.order);
          const milestones = report.milestones.filter((m) => m.phaseOrder === phase.order);
          return (
            <li key={phase.order} className="relative min-w-0" data-testid="roadmap-phase">
              <span
                aria-hidden
                className="absolute top-0.5 -left-[calc(1.25rem+0.75rem+1px)] grid size-6 place-items-center rounded-full border border-brand/50 bg-background text-xs font-semibold text-brand tabular-nums sm:-left-[calc(1.75rem+0.75rem+1px)]"
              >
                {phase.order}
              </span>
              <div className="flex flex-wrap items-baseline justify-between gap-x-3 gap-y-1">
                <h3 className="font-semibold break-words">
                  Phase {phase.order}: {phase.title}
                </h3>
                <p className="text-xs text-muted-foreground tabular-nums">
                  ~{phase.estimatedWeeks} week{phase.estimatedWeeks === 1 ? "" : "s"}
                  {progress && (
                    <>
                      {" "}
                      · {progress.completed}/{progress.total} tasks done
                    </>
                  )}
                </p>
              </div>
              <p className="mt-1 text-sm text-muted-foreground">{phase.objective}</p>
              <ul className="mt-4 grid grid-cols-1 gap-3">
                {tasks.map((task) => (
                  <TaskCard key={task.id} task={task} />
                ))}
              </ul>
              {milestones.map((m) => (
                <div
                  key={m.title}
                  className="mt-4 rounded-xl border border-brand/30 bg-brand/5 p-4"
                  data-testid="roadmap-milestone"
                >
                  <p className="flex items-center gap-2 text-sm font-medium">
                    <Flag className="size-4 shrink-0 text-brand" aria-hidden />
                    <span>
                      <span className="sr-only">Milestone: </span>
                      {m.title}
                    </span>
                  </p>
                  <p className="mt-1 text-sm text-muted-foreground">{m.description}</p>
                  <p className="mt-2 text-xs">
                    <span className="text-muted-foreground">Verified when: </span>
                    {m.verification}
                  </p>
                </div>
              ))}
            </li>
          );
        })}
      </ol>
    </section>
  );
}

function Recommendations({ items }: { items: string[] }) {
  if (items.length === 0) return null;
  return (
    <Card>
      <CardHeader>
        <CardTitle role="heading" aria-level={2}>
          Recommendations
        </CardTitle>
      </CardHeader>
      <CardContent>
        <ul className="grid gap-2 text-sm">
          {items.map((item) => (
            <li key={item} className="flex items-start gap-2">
              <Lightbulb className="mt-0.5 size-4 shrink-0 text-brand" aria-hidden />
              <span className="min-w-0 break-words">{item}</span>
            </li>
          ))}
        </ul>
      </CardContent>
    </Card>
  );
}

export function RoadmapReport({ roadmap, report }: { roadmap: MyRoadmap; report: Report }) {
  return (
    <div className="grid grid-cols-1 gap-6">
      <Overview roadmap={roadmap} report={report} />
      <CurrentProfile profile={report.currentProfile} />
      <SkillGaps report={report} />
      <Timeline roadmap={roadmap} report={report} />
      <Recommendations items={report.recommendations} />
    </div>
  );
}
