import Link from "next/link";
import { CircleCheck, CircleDashed, Info, Lightbulb, ListChecks } from "lucide-react";
import { AnswerFeedback } from "@/components/interview/answer-feedback";
import { ReadinessRing } from "@/components/shared/readiness-ring";
import { Badge } from "@/components/ui/badge";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import type { MyInterview } from "@/lib/data/interview";
import { QUESTION_SOURCE_LABELS, VERDICT_LABELS } from "@/lib/interview/constants";
import { questionLabel } from "@/lib/interview/progress";
import type { InterviewReport as Report } from "@/lib/interview/schema";
import { scoreBand } from "@/lib/interview/scoring";

function ScoreCard({ interview, report }: { interview: MyInterview; report: Report }) {
  return (
    <Card>
      <CardHeader>
        <CardTitle role="heading" aria-level={2}>
          Overall score
        </CardTitle>
        <CardDescription>
          Calculated from your answer evaluations — not by the AI directly.
        </CardDescription>
      </CardHeader>
      <CardContent className="grid gap-8 md:grid-cols-[200px_minmax(0,1fr)] md:items-start">
        <div className="flex flex-col items-center gap-3 text-center">
          <ReadinessRing value={report.overallScore} size={148} label="Overall interview score" />
          <p className="text-2xl font-semibold tabular-nums" data-testid="overall-score">
            {report.overallScore}
            <span className="text-base font-normal text-muted-foreground"> / 100</span>
          </p>
          <p className="text-sm font-medium">{scoreBand(report.overallScore)}</p>
          <p className="text-xs text-muted-foreground">
            {report.answered} answered · {report.skipped} skipped
          </p>
        </div>
        <div className="min-w-0">
          <h3 className="text-sm font-medium">Category scores</h3>
          {report.categories.length === 0 ? (
            <p className="mt-2 text-sm text-muted-foreground">
              Not enough answers to score individual categories.
            </p>
          ) : (
            <ul className="mt-3 grid gap-4">
              {report.categories.map((c) => (
                <li key={c.key}>
                  <div className="flex flex-wrap items-baseline justify-between gap-x-3 text-sm">
                    <span className="font-medium">{c.label}</span>
                    <span className="text-muted-foreground tabular-nums">
                      <span className="text-foreground">{c.score}</span>/100 · based on {c.basedOn}{" "}
                      answers
                    </span>
                  </div>
                  <div
                    className="mt-1.5 h-1.5 overflow-hidden rounded-full bg-muted"
                    role="img"
                    aria-label={`${c.label}: ${c.score} out of 100`}
                  >
                    <div
                      className="h-full rounded-full bg-brand"
                      style={{ width: `${c.score}%` }}
                    />
                  </div>
                </li>
              ))}
            </ul>
          )}
          <details className="mt-5 rounded-lg border bg-muted/30 px-4 py-3 text-xs text-muted-foreground">
            <summary className="cursor-pointer font-medium text-foreground">
              How scores are calculated
            </summary>
            <p className="mt-2">
              Each answer is rated 0–10 on technical accuracy, relevance, completeness, evidence,
              clarity and communication. The answer score is a weighted average (25/20/20/15/10/10);
              technical accuracy is left out for behavioral and HR questions. The overall score is
              the average of all answer scores, with skipped questions counting as 0. Categories
              need at least two answers to be scored.
            </p>
          </details>
          {interview.provider === "mock" && (
            <p className="mt-3 flex items-start gap-2 rounded-lg border border-warning/40 bg-warning/5 px-3 py-2 text-xs">
              <Info className="mt-0.5 size-3.5 shrink-0 text-warning" aria-hidden />
              Generated by the deterministic mock provider for development. It is not an AI
              assessment.
            </p>
          )}
        </div>
      </CardContent>
    </Card>
  );
}

function NoteList({
  title,
  items,
  icon: Icon,
  tone,
  empty,
}: {
  title: string;
  items: { text: string; questionLabel: string }[];
  icon: typeof CircleCheck;
  tone: string;
  empty: string;
}) {
  return (
    <Card>
      <CardHeader>
        <CardTitle role="heading" aria-level={2}>
          {title}
        </CardTitle>
        <CardDescription>From the feedback on your answers.</CardDescription>
      </CardHeader>
      <CardContent>
        {items.length === 0 ? (
          <p className="text-sm text-muted-foreground">{empty}</p>
        ) : (
          <ul className="grid gap-2 text-sm">
            {items.map((s) => (
              <li key={s.text} className="flex gap-2">
                <Icon className={`mt-0.5 size-4 shrink-0 ${tone}`} aria-hidden />
                <span className="min-w-0 break-words">
                  {s.text}{" "}
                  <span className="text-xs text-muted-foreground">({s.questionLabel})</span>
                </span>
              </li>
            ))}
          </ul>
        )}
      </CardContent>
    </Card>
  );
}

export function InterviewReport({ interview, report }: { interview: MyInterview; report: Report }) {
  const next = report.nextPractice;
  const hasNext = next.roadmapTasks.length + next.jobGaps.length + next.cvSkills.length > 0;
  return (
    <div className="grid grid-cols-1 gap-6">
      <ScoreCard interview={interview} report={report} />
      <div className="grid grid-cols-1 gap-6 lg:grid-cols-2">
        <NoteList
          title="Strengths"
          items={report.strengths}
          icon={CircleCheck}
          tone="text-success"
          empty="No clear strengths could be identified from the answers given."
        />
        <NoteList
          title="Improvement areas"
          items={report.improvements}
          icon={CircleDashed}
          tone="text-warning"
          empty="No specific gaps were noted in your answers."
        />
      </div>

      <Card>
        <CardHeader>
          <CardTitle role="heading" aria-level={2}>
            Questions to review
          </CardTitle>
          <CardDescription>
            Questions with partial, weakly supported or skipped answers.
          </CardDescription>
        </CardHeader>
        <CardContent>
          {report.questionsToReview.length === 0 ? (
            <p className="text-sm text-muted-foreground">
              Nothing to review — every answer was strong.
            </p>
          ) : (
            <ul className="grid gap-3">
              {report.questionsToReview.map((q) => (
                <li key={q.questionId} className="min-w-0 rounded-lg border p-3.5">
                  <div className="flex flex-wrap items-center gap-2 text-xs">
                    <span className="font-medium">{q.label}</span>
                    <Badge variant="outline" className="font-normal">
                      {q.verdict ? VERDICT_LABELS[q.verdict] : "Skipped"}
                    </Badge>
                    {q.score !== null && (
                      <span className="text-muted-foreground tabular-nums">{q.score}/100</span>
                    )}
                  </div>
                  <p className="mt-1.5 text-sm break-words">{q.prompt}</p>
                  <a
                    href={`#transcript-${q.questionId}`}
                    className="mt-0.5 inline-block rounded-sm py-1.5 text-xs text-brand hover:underline"
                  >
                    {q.verdict
                      ? "See your answer and feedback"
                      : "See the question in the transcript"}
                  </a>
                </li>
              ))}
            </ul>
          )}
        </CardContent>
      </Card>

      <Card>
        <CardHeader>
          <CardTitle role="heading" aria-level={2}>
            Recommendations
          </CardTitle>
        </CardHeader>
        <CardContent>
          <ul className="grid gap-2 text-sm">
            {report.recommendations.map((r) => (
              <li key={r} className="flex gap-2">
                <Lightbulb className="mt-0.5 size-4 shrink-0 text-brand" aria-hidden />
                <span className="min-w-0 break-words">{r}</span>
              </li>
            ))}
          </ul>
        </CardContent>
      </Card>

      <Card>
        <CardHeader>
          <CardTitle role="heading" aria-level={2}>
            Next practice
          </CardTitle>
          <CardDescription>
            Linked only to your real roadmap tasks, Job Match gaps and CV skills.
          </CardDescription>
        </CardHeader>
        <CardContent className="grid gap-5 text-sm">
          {!hasNext && (
            <p className="text-muted-foreground">
              No matching roadmap tasks or skill gaps. Try another interview with a different focus.
            </p>
          )}
          {next.roadmapTasks.length > 0 && (
            <div>
              <h3 className="font-medium">From your career roadmap</h3>
              <ul className="mt-1.5 grid gap-1">
                {next.roadmapTasks.map((t) => (
                  <li key={t.id} className="flex gap-2">
                    <ListChecks className="mt-0.5 size-4 shrink-0 text-brand" aria-hidden />
                    <span className="min-w-0 break-words">
                      {t.title} <span className="text-xs text-muted-foreground">({t.skill})</span>
                    </span>
                  </li>
                ))}
              </ul>
              <Link
                href="/dashboard/roadmap"
                className="mt-1 inline-block rounded-sm py-1.5 text-xs text-brand hover:underline"
              >
                Open Career Roadmap
              </Link>
            </div>
          )}
          {next.jobGaps.length > 0 && (
            <div>
              <h3 className="font-medium">Job Match skills to strengthen</h3>
              <div className="mt-1.5 flex flex-wrap gap-1.5">
                {next.jobGaps.map((g) => (
                  <Badge key={g.skill} variant="secondary" className="font-normal">
                    {g.skill} ·{" "}
                    {g.match === "MISSING" ? "not demonstrated in your CV" : "partial match"}
                  </Badge>
                ))}
              </div>
            </div>
          )}
          {next.cvSkills.length > 0 && (
            <div>
              <h3 className="font-medium">CV skills you explained well</h3>
              <p className="text-xs text-muted-foreground">
                Keep using these as examples in interviews.
              </p>
              <div className="mt-1.5 flex flex-wrap gap-1.5">
                {next.cvSkills.map((s) => (
                  <Badge key={s} variant="secondary" className="font-normal">
                    {s}
                  </Badge>
                ))}
              </div>
            </div>
          )}
        </CardContent>
      </Card>

      <section aria-labelledby="transcript-heading" className="min-w-0">
        <h2 id="transcript-heading" className="mb-3 text-lg font-semibold tracking-tight">
          Full transcript
        </h2>
        <ol className="grid grid-cols-1 gap-3">
          {interview.questions.map((q) => (
            <li key={q.id} id={`transcript-${q.id}`} className="min-w-0 scroll-mt-24">
              <details className="rounded-xl border bg-card px-4 py-3">
                <summary className="cursor-pointer text-sm">
                  <span className="font-medium">{questionLabel(q)}</span>
                  <span className="text-muted-foreground">
                    {" "}
                    ·{" "}
                    {q.status === "SKIPPED"
                      ? "Skipped"
                      : q.answer?.score != null
                        ? `${q.answer.score}/100`
                        : "Answered"}
                  </span>
                </summary>
                <div className="mt-3 grid gap-4">
                  <p className="text-sm font-medium break-words">{q.prompt}</p>
                  <p className="text-xs text-muted-foreground">
                    Source: {QUESTION_SOURCE_LABELS[q.source]} · {q.sourceReason}
                  </p>
                  {q.answer ? (
                    <>
                      <div>
                        <h3 className="text-sm font-medium">Your answer</h3>
                        <p className="mt-1 text-sm break-words whitespace-pre-wrap text-muted-foreground">
                          {q.answer.content}
                        </p>
                      </div>
                      <AnswerFeedback answer={q.answer} headingLevel={4} />
                    </>
                  ) : (
                    <p className="text-sm text-muted-foreground">Skipped.</p>
                  )}
                </div>
              </details>
            </li>
          ))}
        </ol>
      </section>
    </div>
  );
}
